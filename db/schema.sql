 WHERE p.po_page_id IS NULL AND b.pb_id = p.po_batch_id AND b.pb_page_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS js_fb_post_page_idx ON js_fb_post (po_page_id, po_status);

