  WHERE m_status = 3 AND m_is_incoming = 2;
CREATE INDEX IF NOT EXISTS js_message_sent_time_idx ON js_message (m_in_process_on)
  WHERE m_status = 3 AND m_is_incoming = 2;
-- Admin dashboard "sent today" / "last message sent" (by status update time)
