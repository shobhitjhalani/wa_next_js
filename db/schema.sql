  fp_name text NOT NULL DEFAULT '',
  fp_token text NOT NULL,
  fp_user_id integer NOT NULL DEFAULT 0,      -- client account (js_user), 0 = none
  fp_emp_id integer NOT NULL DEFAULT 0,
  fp_created_on integer NOT NULL DEFAULT 0
);

-- One CSV upload.
CREATE TABLE IF NOT EXISTS js_fb_post_batch (
  pb_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pb_page_id integer NOT NULL REFERENCES js_fb_page (fp_id) ON DELETE CASCADE,
  pb_file text NOT NULL DEFAULT '',
  pb_total integer NOT NULL DEFAULT 0,
  pb_emp_id integer NOT NULL DEFAULT 0,
  pb_created_on integer NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS js_fb_post_batch_idx ON js_fb_post_batch (pb_id DESC);

-- One post of a batch; the worker job "fb-posts" publishes it at po_scheduled_at.
CREATE TABLE IF NOT EXISTS js_fb_post (
  po_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  po_batch_id integer NOT NULL REFERENCES js_fb_post_batch (pb_id) ON DELETE CASCADE,
  po_line integer NOT NULL DEFAULT 0,         -- CSV line number
  po_message text NOT NULL DEFAULT '',
  po_link text NOT NULL DEFAULT '',
  po_image_url text NOT NULL DEFAULT '',
  po_scheduled_at integer NOT NULL DEFAULT 0,
  po_status smallint NOT NULL DEFAULT 1,      -- 1 Queued · 2 Posting · 3 Posted · 4 Failed · 5 Cancelled
  po_fb_id text NOT NULL DEFAULT '',          -- Facebook post id
  po_error text NOT NULL DEFAULT '',
  po_posted_on integer NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS js_fb_post_batch_line_idx ON js_fb_post (po_batch_id, po_line);
CREATE INDEX IF NOT EXISTS js_fb_post_due_idx ON js_fb_post (po_scheduled_at) WHERE po_status = 1;

-- One upload can go to several Pages: each post row carries its Page (pb_page_id is only set on old single-Page uploads).
