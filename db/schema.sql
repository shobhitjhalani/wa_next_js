-- =====================================================================
-- wa_next_js — PostgreSQL schema
--
-- Same js_* tables and column names as the Laravel / legacy MySQL app, so
-- data copies across 1:1 (scripts/migrate-from-mysql.ts). Differences:
--   * strings are TEXT (no silent truncation / overflow errors);
--   * columns MySQL compared case-insensitively by collation (usernames,
--     emails, group names) are CITEXT;
--   * "ON UPDATE CURRENT_TIMESTAMP" columns are maintained by a trigger;
--   * indexes are rebuilt around the queries the app actually runs, with
--     partial indexes for the hot queue / report paths on js_message.
--
-- Idempotent: safe to run on an existing database (npm run db:migrate).
-- =====================================================================

SET client_min_messages = warning;
CREATE EXTENSION IF NOT EXISTS citext;

CREATE OR REPLACE FUNCTION wa_touch_updated() RETURNS trigger AS $$
BEGIN
  NEW := json_populate_record(NEW, json_build_object(TG_ARGV[0], now()));
  RETURN NEW;
END $$ LANGUAGE plpgsql;

