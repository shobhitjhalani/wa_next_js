-- ------------------------------------------------------------ template message limit

-- js_user.u_msg_limit: template messages the account may send in total (0 = unlimited).
-- u_msg_used counts template messages WhatsApp accepted and did not report as failed:
-- the sender reserves a slot before each send and the status queue refunds failures
-- (src/lib/services/template-limit.ts). Added once, with a backfill from the message
-- history so existing limits keep their meaning.
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM information_schema.columns
                  WHERE table_schema = current_schema() AND table_name = 'js_user' AND column_name = 'u_msg_used') THEN
    ALTER TABLE js_user ADD COLUMN u_msg_used integer NOT NULL DEFAULT 0;
    UPDATE js_user u SET u_msg_used = s.n
      FROM (SELECT m_user_id, COUNT(*)::int AS n FROM js_message
             WHERE m_is_incoming = 2 AND m_status = 3 AND m_dstatus = 0 AND COALESCE(m_message_id, '') <> ''
               AND m_msg_type IN ('template', 'flow', 'carousel', 'Authentication')
               AND COALESCE(m_delivery_status, '') NOT IN ('failed', 'error')
             GROUP BY m_user_id) s
     WHERE u.u_id = s.m_user_id;
  END IF;
END $$;

-- ------------------------------------------------------------ flow (form) responses

-- jsonb from legacy text that may hold raw newlines / unescaped quotes; NULL when it can't be read
CREATE OR REPLACE FUNCTION wa_try_jsonb(t text) RETURNS jsonb AS $$
BEGIN
  RETURN replace(replace(replace(t, E'\r', '\r'), E'\n', '\n'), E'\t', '\t')::jsonb;
EXCEPTION WHEN others THEN RETURN NULL;
END $$ LANGUAGE plpgsql IMMUTABLE;

-- One row per WhatsApp Flow submission (interactive nfm_reply), written by the webhook.
-- Created once with a backfill from js_incoming_log (il_type = 'flow'); old rows start as read.
DO $$
BEGIN
  IF to_regclass('js_flow_responses') IS NULL THEN
    CREATE TABLE js_flow_responses (
      fr_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      fr_user_id integer NOT NULL,
      fr_m_id bigint,                              -- incoming js_message row
      fr_wa_id text,                               -- WhatsApp message id of the reply
      fr_mobile_no text,
      fr_sender_name text,
      fr_template_name text,                       -- flow template the customer answered
      fr_response jsonb NOT NULL DEFAULT '{}',     -- the flow's response_json
      fr_is_read smallint NOT NULL DEFAULT 2,      -- 1 read, 2 unread
      fr_created_on integer NOT NULL DEFAULT 0
    );
    INSERT INTO js_flow_responses (fr_user_id, fr_m_id, fr_wa_id, fr_mobile_no, fr_sender_name, fr_template_name, fr_response, fr_is_read, fr_created_on)
    SELECT l.il_user_id, m.m_id, l.j->>'message_id', l.il_sender_phone_no, l.j->>'sender_name', t.m_msg_template_name,
           CASE WHEN jsonb_typeof(l.j->'response') = 'object' THEN l.j->'response' ELSE jsonb_build_object('_raw', l.il_response) END,
           1, COALESCE(m.m_created_on, 0)
      FROM (SELECT DISTINCT ON (COALESCE(x.j->>'message_id', x.il_id::text)) x.*   -- WhatsApp retried some deliveries
              FROM (SELECT il_id, il_user_id, il_sender_phone_no, il_response, wa_try_jsonb(il_response) AS j
                      FROM js_incoming_log WHERE il_type = 'flow' AND il_user_id > 0) x
             ORDER BY COALESCE(x.j->>'message_id', x.il_id::text), x.il_id) l
      LEFT JOIN js_message m ON m.m_message_id = l.j->>'message_id' AND m.m_is_incoming = 1
      LEFT JOIN LATERAL (
        SELECT s.m_msg_template_name FROM js_message s
         WHERE m.m_id IS NOT NULL AND s.m_user_id = m.m_user_id AND s.m_mobile_no = m.m_mobile_no
           AND s.m_id < m.m_id AND s.m_is_incoming = 2 AND s.m_msg_type = 'flow'
         ORDER BY s.m_id DESC LIMIT 1) t ON true
     ORDER BY l.il_id;
  END IF;
END $$;
CREATE INDEX IF NOT EXISTS js_flow_responses_user_idx ON js_flow_responses (fr_user_id, fr_id);
CREATE UNIQUE INDEX IF NOT EXISTS js_flow_responses_wa_idx ON js_flow_responses (fr_wa_id) WHERE fr_wa_id IS NOT NULL;
